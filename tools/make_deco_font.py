#!/usr/bin/env python3
"""Generate the Art Deco numerals in src/epd_deco_font.c.

Deco figures are geometric constructions, so that is how they are drawn here:
each digit is a union of ellipse rings, slabs and diagonals in a 30 x 44 cell,
sampled 4 x 4 per pixel and thresholded. Two constants carry the style --

    THICK  the weight of a vertical stroke or the flank of a bowl
    THIN   the weight of a horizontal, roughly a third of THICK

-- and that contrast is what reads as Deco rather than as a generic sans.

Run from the project root:  python3 tools/make_deco_font.py
Add --preview FILE.ppm to also drop a 4x proof sheet of the ten figures.
"""
import sys
from pathlib import Path

W, H = 30, 44
THICK, THIN = 7.0, 3.0
SUBSAMPLES = 4
OUT = Path("src/epd_deco_font.c")

# --- shape primitives, all in glyph space: x right, y down, (0,0) top left ---

def rect(x0, y0, x1, y1):
    return lambda x, y: x0 <= x <= x1 and y0 <= y <= y1

def ring(cx, cy, rx, ry, tx=THICK, ty=THIN):
    """Elliptical ring, tx thick at the flanks and ty at the crown."""
    ix, iy = rx - tx, ry - ty
    def inside(x, y):
        u, v = (x - cx) / rx, (y - cy) / ry
        if u * u + v * v > 1.0:
            return False
        if ix <= 0 or iy <= 0:
            return True
        u, v = (x - cx) / ix, (y - cy) / iy
        return u * u + v * v >= 1.0
    return inside

def poly(points):
    """Even-odd point-in-polygon, for the diagonals."""
    def inside(x, y):
        hit = False
        n = len(points)
        for i in range(n):
            x0, y0 = points[i]
            x1, y1 = points[(i + 1) % n]
            if (y0 > y) != (y1 > y):
                if x < x0 + (y - y0) * (x1 - x0) / (y1 - y0):
                    hit = not hit
        return hit
    return inside

def clip(shape, test):
    return lambda x, y: shape(x, y) and test(x, y)

def union(*shapes):
    return lambda x, y: any(s(x, y) for s in shapes)

# --- the ten figures ---------------------------------------------------------

def digits():
    d = {}

    # 0 -- a true ellipse, flanks heavy and crown light.
    d[0] = ring(15, 22, 14.5, 22)

    # 1 -- a bare slab, as on the dial in the photograph.
    d[1] = rect(11.5, 0, 18.5, 44)

    # 2 -- shoulder, hairline diagonal, heavy foot.
    d[2] = union(
        clip(ring(15, 14, 13.5, 14), lambda x, y: y <= 11 or (x >= 15 and y <= 21)),
        poly([(18, 17), (24, 21), (9, 38.5), (3, 38.5)]),
        rect(2, 38.5, 28, 43.5),
    )

    # 3 -- two right-hand bowls, the lower one the larger.
    d[3] = union(
        clip(ring(14.5, 12, 13, 12, 6.5, 3), lambda x, y: x >= 10 or y <= 3),
        clip(ring(14, 30.5, 14, 13.5), lambda x, y: x >= 10 or y >= 40),
        rect(12, 19.5, 20, 23),
    )

    # 4 -- heavy stem, hairline diagonal, hairline bar.
    d[4] = union(
        rect(17, 0, 24, 44),
        poly([(17, 0), (17, 7), (6, 28), (1, 28)]),
        rect(1, 28, 29, 31.5),
    )

    # 5 -- flat cap, short stem, then a bowl swung off the shoulder.
    d[5] = union(
        rect(3, 0, 27, 3.5),
        rect(3, 0, 9.5, 19),
        rect(3, 15.5, 15, 19.5),
        clip(ring(15, 29.5, 14, 14.5), lambda x, y: not (x < 15 and y < 27)),
    )

    # 6 -- closed bowl under a spine that sweeps up and over to the right.
    d[6] = union(
        ring(15, 30, 14, 13.5),
        clip(ring(15, 22, 14, 22), lambda x, y: x <= 15 or y <= 6),
    )

    # 7 -- heavy cap over a diagonal that keeps its weight.
    d[7] = union(
        rect(1, 0, 29, 5),
        poly([(21, 5), (29, 5), (17, 44), (9, 44)]),
    )

    # 8 -- small bowl over a larger one, the Deco tell.
    d[8] = union(
        ring(15, 11.5, 11.5, 11.5, 6, 3),
        ring(15, 30.5, 14, 13.5),
    )

    # 9 -- the 6 turned through half a turn, so the pair stay a pair.
    d[9] = None
    return d

# --- rasterising -------------------------------------------------------------

def raster(shape):
    """Sample `shape` into a list of H rows of W booleans."""
    step = 1.0 / SUBSAMPLES
    need = SUBSAMPLES * SUBSAMPLES / 2
    rows = []
    for py in range(H):
        row = []
        for px in range(W):
            hits = 0
            for sy in range(SUBSAMPLES):
                y = py + (sy + 0.5) * step
                for sx in range(SUBSAMPLES):
                    if shape(px + (sx + 0.5) * step, y):
                        hits += 1
            row.append(hits >= need)
        rows.append(row)
    return rows

def rot180(rows):
    return [list(reversed(r)) for r in reversed(rows)]

def trim(rows):
    """Drop blank columns either side; glyphs are set on their own widths."""
    cols = [c for c in range(W) if any(r[c] for r in rows)]
    if not cols:
        return 0, rows
    lo, hi = min(cols), max(cols)
    return hi - lo + 1, [r[lo:hi + 1] for r in rows]

# --- emitting ----------------------------------------------------------------

BANNER = """/*
 * epd_deco_font.c - Art Deco numerals, 0-9.
 *
 * GENERATED by tools/make_deco_font.py -- do not edit by hand. Change the
 * geometry in the script and run it again from the project root.
 *
 * Each figure is drawn as a union of ellipse rings, slabs and diagonals on a
 * %d x %d cell, with a %g px flank against a %g px crown. That thick-to-thin
 * contrast, and the true-circle geometry underneath it, is what makes the set
 * Deco; it is the same logic the numerals on the reference dial are built on.
 *
 * Rows are one word each, leftmost pixel in bit 0. Glyphs are trimmed to their
 * ink, so each carries its own width and the dial can set them proportionally.
 */
#include "epd_deco_font.h"

_Static_assert(DECO_GLYPH_H == %d, "epd_deco_font.h and the generator disagree on height");

const deco_glyph_t DECO_DIGITS[10] = {
"""

def main():
    shapes = digits()
    glyphs = {}
    for n in range(10):
        if shapes[n] is None:
            continue
        glyphs[n] = raster(shapes[n])
    glyphs[9] = rot180(glyphs[6])

    body = []
    for n in range(10):
        w, rows = trim(glyphs[n])
        words = ", ".join(
            "0x%08X" % sum(1 << c for c, on in enumerate(row) if on) for row in rows
        )
        body.append("    /* %d */ {%d, {%s}},\n" % (n, w, words))

    text = BANNER % (W, H, THICK, THIN, H) + "".join(body) + "};\n"
    OUT.write_text(text)
    print("wrote %s (%d bytes)" % (OUT, len(text)))

    if "--preview" not in sys.argv:
        return

    # A proof sheet at 4x, for eyeballing the set before it goes near a panel.
    preview = Path(sys.argv[sys.argv.index("--preview") + 1])
    zoom, gap = 4, 2
    total_w = sum(trim(glyphs[n])[0] + gap for n in range(10)) * zoom
    ppm = ["P6\n%d %d\n255\n" % (total_w, H * zoom)]
    pix = bytearray()
    for py in range(H * zoom):
        for n in range(10):
            w, rows = trim(glyphs[n])
            for px in range((w + gap) * zoom):
                on = px // zoom < w and rows[py // zoom][px // zoom]
                pix += b"\x00\x00\x00" if on else b"\xff\xff\xff"
    preview.write_bytes(ppm[0].encode() + bytes(pix))
    print("wrote %s" % preview)

if __name__ == "__main__":
    main()
